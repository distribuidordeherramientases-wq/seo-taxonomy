defined('ABSPATH') || exit;

final class SEO_Solucionador_Export {
    const SCHEMA = 'seo-solucionador-export-v6';

    public static function init() {
        add_action('admin_post_seo_solucionador_export_json', array(__CLASS__, 'download'));
        add_action('admin_post_seo_solucionador_export_report_json', array(__CLASS__, 'download_simple_report'));
    }

    public static function download() {
        if (!current_user_can('manage_options')) {
            wp_die('No tienes permisos para exportar Solucionador.');
        }
        check_admin_referer('seo_solucionador_export_json');
        SEO_Solucionador_DB::maybe_install();
        $initialization = SEO_Solucionador_Engine::ensure_initialized(180);
        if (is_wp_error($initialization)) {
            wp_die(esc_html($initialization->get_error_message()));
        }

        $payload = self::build_payload();
        $json = wp_json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
        );
        if (!is_string($json)) {
            wp_die('No se pudo generar el JSON de Solucionador.');
        }

        while (ob_get_level() > 0) {
            @ob_end_clean();
        }

        $filename = sanitize_file_name('seo-solucionador-' . wp_date('Ymd-His') . '.json');
        nocache_headers();
        header('Content-Type: application/json; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('X-Content-Type-Options: nosniff');
        header('Content-Length: ' . strlen($json));
        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Raw JSON download generated by wp_json_encode(); HTML escaping would corrupt the payload.
        echo $json;
        exit;
    }

